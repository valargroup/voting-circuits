// Hash-to-curve personalization for synthetic padding `g_d_pad` points.
//
// Domain-separated from Orchard's `KEY_DIVERSIFICATION_PERSONALIZATION`
// (`"z.cash:Orchard-gd"`) so that `g_d_pad = hash_to_curve(PADDING_PERSONALIZATION)(...)`
// is not generated by the same diversified-address construction as real Orchard
// bases. Any accidental point collision is treated as a negligible hash-to-curve
// collision rather than a burned diversifier-index overlap.
const PADDING_PERSONALIZATION: &str = "shielded-vote/padding-v1";

/// Rho and rseed for a single padded note, captured during Phase 1 (PCZT construction).
#[derive(Clone, Debug)]
pub struct PaddedNoteData {
    /// Rho bytes (32 bytes, LE encoding of pallas::Base).
    pub rho: [u8; 32],
    /// Random seed bytes (32 bytes).
    pub rseed: [u8; 32],
}

/// Randomness captured during Phase 1 (PCZT construction) that must be reused
/// in Phase 2 (ZK proving) so the prover commits to the same nf_signed/cmx_new
/// that the signer committed to via the ZIP-244 sighash.
#[derive(Clone, Debug)]
pub struct PrecomputedRandomness {
    /// Rho + rseed for each padded note (0–4 entries).
    pub padded_notes: Vec<PaddedNoteData>,
    /// Rseed for the signed (keystone) note.
    pub rseed_signed: [u8; 32],
    /// Rseed for the output note.
    pub rseed_output: [u8; 32],
}

/// Which precomputed note input failed validation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PrecomputedRandomnessLocation {
    /// A padded note entry by index in `PrecomputedRandomness::padded_notes`.
    PaddedNote(usize),
    /// The synthetic signed note.
    SignedNote,
    /// The output note.
    OutputNote,
}

/// Input for a single real note in the delegation.
#[derive(Debug)]
pub struct RealNoteInput {
    /// The note being delegated.
    pub note: Note,
    /// The note's full viewing key.
    pub fvk: FullViewingKey,
    /// Merkle authentication path for the note commitment.
    pub merkle_path: MerklePath,
    /// IMT non-membership proof for this note's nullifier.
    ///
    /// This must satisfy [`ImtProofData`]'s tree contract and authenticate to
    /// the same nullifier IMT root used for the bundle.
    pub imt_proof: ImtProofData,
    /// Whether this note uses the internal (change) or external scope.
    pub scope: Scope,
}

/// Complete delegation bundle: a single circuit proving all 15 conditions.
#[derive(Debug)]
pub struct DelegationBundle {
    /// The merged delegation circuit.
    pub circuit: circuit::Circuit,
    /// Public inputs (14 field elements).
    pub instance: circuit::Instance,
}

// `ExtractP` from the Orchard spec: the x-coordinate of a non-identity Pallas
// point. Panics on identity.
// Note: Orchard's `spec::extract_p` is `pub(crate)`; we mirror it here.
fn point_x(point: &pallas::Point) -> pallas::Base {
    point_x_opt(point).expect("ExtractP requires a non-identity Pallas point")
}

fn point_x_opt(point: &pallas::Point) -> Option<pallas::Base> {
    point
        .to_affine()
        .coordinates()
        .into_option()
        .map(|coords| *coords.x())
}

// Expands a 32-byte compressed encoding into a stream of little-endian bits.
// Orchard’s note commitment hashes `g_d` and `pk_d` as
// little-endian bits of their 32-byte compressed encodings.
fn byte_bits(bytes: [u8; 32]) -> impl Iterator<Item = bool> {
    bytes
        .into_iter()
        .flat_map(|byte| (0..8).map(move |bit| ((byte >> bit) & 1) == 1))
}

// Expands a 64-bit little-endian integer into a stream of little-endian bits.
// Orchard’s note commitment hashes `value` as a 64-bit little-endian integer.
fn u64_bits(value: u64) -> impl Iterator<Item = bool> {
    value
        .to_le_bytes()
        .into_iter()
        .flat_map(|byte| (0..8).map(move |bit| ((byte >> bit) & 1) == 1))
}

// Derives the external IVK scalar from the full viewing key and spend validating key.
// Used to construct padding `(g_d_pad, pk_d_pad)` pairs such that the in-circuit
// `pk_d = [selected_ivk] * g_d` check (condition 11) holds against the same ivk
// the circuit derives in condition 5. Padding always uses `is_internal = false`,
// so the external rivk is the correct scope.
// Note: Orchard's `FullViewingKey::to_ivk` does not expose the inner Ivk scalar;
// if it did (e.g. `fvk.ivk_scalar(scope)`), we could drop this re-implementation.
fn external_ivk_scalar(fvk: &FullViewingKey, ak: &SpendValidatingKey) -> pallas::Scalar {
    let ak_point: pallas::Point = ak.into();
    let ak_x = point_x(&ak_point);
    let rivk = fvk.rivk(Scope::External).inner();
    let domain = sinsemilla::CommitDomain::new(COMMIT_IVK_PERSONALIZATION);
    let ivk = domain
        .short_commit(
            iter::empty()
                .chain(ak_x.to_le_bits().iter().by_vals().take(L_ORCHARD_BASE))
                .chain(
                    fvk.nk()
                        .inner()
                        .to_le_bits()
                        .iter()
                        .by_vals()
                        .take(L_ORCHARD_BASE),
                ),
            &rivk,
        )
        .expect("external ivk must not be bottom");
    base_to_scalar(ivk).expect("external ivk must fit in the scalar field")
}

// Wraps a `pallas::Point` as `NonIdentityPallasPoint` without panicking on identity.
//
// Synthesized padding points come from `hash_to_curve` and scalar multiplication
// by `ivk`; both are cryptographically non-identity (identity from `hash_to_curve`
// is negligible, and `ivk = 0` is already rejected by `CommitIvk`'s ⊥ branch upstream).
// We validate here so the invariant fails at the construction site rather than
// silently flowing into the witness — the in-circuit `NonIdentityPoint::new`
// would catch identity at proof time, but a build-time error is cheaper to debug.
fn non_identity_padding_point(
    point: pallas::Point,
    slot_index: usize,
    component: &'static str,
) -> Result<NonIdentityPallasPoint, DelegationBuildError> {
    NonIdentityPallasPoint::from_bytes(&point.to_affine().to_bytes())
        .into_option()
        .ok_or(DelegationBuildError::InvalidPaddingPoint {
            slot_index,
            component,
        })
}

fn validate_padding_slot_index(slot_index: usize) -> Result<(), DelegationBuildError> {
    if (1..circuit::MAX_REAL_NOTES).contains(&slot_index) {
        Ok(())
    } else {
        Err(DelegationBuildError::InvalidPaddingSlotIndex { slot_index })
    }
}

// Derives the synthetic `(g_d_pad, pk_d_pad)` pair for padding slot `slot_index`.
// `g_d_pad` is domain-separated from Orchard's `DiversifyHash`, so the pair is
// intentionally not a valid `orchard::Address`. `pk_d_pad = [ivk] * g_d_pad`
// satisfies condition 11 by construction (callers must pass the external ivk,
// since padding pins `is_internal = false`). Both points are wrapped as
// `NonIdentityPallasPoint` via `non_identity_padding_point` so the invariant fails at
// the builder rather than at proof time.
fn padding_points(
    slot_index: usize,
    ivk: pallas::Scalar,
) -> Result<(NonIdentityPallasPoint, NonIdentityPallasPoint), DelegationBuildError> {
    validate_padding_slot_index(slot_index)?;
    let slot_index_u32 =
        u32::try_from(slot_index).expect("validated padding slot index fits in u32");
    let g_d_pad =
        pallas::Point::hash_to_curve(PADDING_PERSONALIZATION)(&slot_index_u32.to_le_bytes());
    let pk_d_pad = g_d_pad * ivk;
    Ok((
        non_identity_padding_point(g_d_pad, slot_index, "g_d")?,
        non_identity_padding_point(pk_d_pad, slot_index, "pk_d")?,
    ))
}

// Generates a random seed for a given rho.
// The random seed is used to derive the psi and rcm for the note.
// Note: Orchard's RandomSeed::random is not exposed. If it was exposed,
// we could use it here instead of sampling a random seed.
fn random_seed_for_rho(rho: &Rho, rng: &mut impl RngCore) -> RandomSeed {
    loop {
        let mut rseed = [0u8; 32];
        rng.fill_bytes(&mut rseed);
        let rseed = RandomSeed::from_bytes(rseed, rho);
        if bool::from(rseed.is_some()) {
            return rseed.unwrap();
        }
    }
}

// Derives the note commitment point for a synthetic padding note.
// Orchard has this low-level operation internally as NoteCommitment::derive,
// but does not expose it as a public helper. Mirror it here so padding can use
// domain-separated synthetic (g_d, pk_d) points.
//
// Sinsemilla returns `None` precisely when the commitment would be the identity
// ("bottom"), so callers must convert that into a recoverable build error.
fn note_commitment_point(
    g_d: pallas::Point,
    pk_d: pallas::Point,
    value: NoteValue,
    rho: pallas::Base,
    psi: pallas::Base,
    rcm: pallas::Scalar,
) -> Option<pallas::Point> {
    let domain = sinsemilla::CommitDomain::new(NOTE_COMMITMENT_PERSONALIZATION);
    // Mirrors Orchard NoteCommit while allowing synthetic padding points.
    domain
        .commit(
            iter::empty()
                .chain(byte_bits(g_d.to_affine().to_bytes()))
                .chain(byte_bits(pk_d.to_affine().to_bytes()))
                .chain(u64_bits(value.inner()).take(L_VALUE))
                .chain(rho.to_le_bits().iter().by_vals().take(L_ORCHARD_BASE))
                .chain(psi.to_le_bits().iter().by_vals().take(L_ORCHARD_BASE)),
            &rcm,
        )
        .into_option()
}

// Derives the note nullifier for a given note.
// Note: Orchard has this low-level operation internally as Note::nullifier,
// but does not expose it as a public helper. Mirror it here so padding can use
// the same derivation logic.
fn derive_note_nullifier(
    nk: pallas::Base,
    rho: pallas::Base,
    psi: pallas::Base,
    cm: pallas::Point,
) -> Option<pallas::Base> {
    let k = pallas::Point::hash_to_curve("z.cash:Orchard")(b"K");
    let prf_nf = poseidon_hash_2(nk, rho);
    // Pallas base elements embed directly into the larger scalar field.
    let scalar = pallas::Scalar::from_repr((prf_nf + psi).to_repr())
        .expect("Pallas base field is smaller than its scalar field");
    point_x_opt(&(k * scalar + cm))
}

/// Off-circuit `(cmx, nullifier)` for a synthetic padding slot, in canonical
/// little-endian byte encoding.
///
/// The values match what the delegation circuit constrains for the padded
/// slot, so downstream consumers (PCZT metadata, PIR precompute, IMT
/// non-membership lookups) can reference the same padding-slot commitment
/// x-coordinate and real Orchard nullifier the prover witnesses without
/// re-implementing the synthetic padding derivation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct SyntheticPaddingNoteParts {
    /// Extracted x-coordinate of the synthetic padding note commitment.
    pub cmx: [u8; 32],
    /// Real Orchard nullifier of the synthetic padding note (the one
    /// `gov_null` is derived from).
    pub nullifier: [u8; 32],
}

struct SyntheticPaddingDerivation {
    g_d_pad: NonIdentityPallasPoint,
    pk_d_pad: NonIdentityPallasPoint,
    psi: pallas::Base,
    rcm: orchard::note::NoteCommitTrapdoor,
    cm: pallas::Point,
    cmx: pallas::Base,
    real_nf: pallas::Base,
}

// Derives every off-circuit value for a synthetic padding note from one shared
// construction, so public helper output and in-circuit witnesses cannot drift.
fn derive_synthetic_padding_note(
    nk: pallas::Base,
    ivk: pallas::Scalar,
    slot_index: usize,
    rho: Rho,
    rseed: RandomSeed,
    location: PrecomputedRandomnessLocation,
) -> Result<SyntheticPaddingDerivation, DelegationBuildError> {
    // Padding uses synthetic address components bound to the external IVK; the
    // rho-scoped seed then supplies the Orchard commitment randomness.
    let (g_d_pad, pk_d_pad) = padding_points(slot_index, ivk)?;
    let psi = rseed.psi(&rho);
    let rcm = rseed.rcm(&rho);

    // Commitment and nullifier derivation can bottom out only in negligible
    // group edge cases; surface those as build errors at the caller's location.
    let cm = note_commitment_point(
        *g_d_pad,
        *pk_d_pad,
        NoteValue::ZERO,
        rho.into_inner(),
        psi,
        rcm.inner(),
    )
    .ok_or(DelegationBuildError::InvalidPaddingNoteCommitment { location })?;
    let cmx =
        point_x_opt(&cm).ok_or(DelegationBuildError::InvalidPaddingNoteCommitment { location })?;
    let real_nf = derive_note_nullifier(nk, rho.into_inner(), psi, cm)
        .ok_or(DelegationBuildError::InvalidPaddingNullifier { location })?;

    Ok(SyntheticPaddingDerivation {
        g_d_pad,
        pk_d_pad,
        psi,
        rcm,
        cm,
        cmx,
        real_nf,
    })
}

/// Computes the off-circuit `(cmx, nullifier)` for a synthetic padding slot
/// from the same construction the delegation builder uses in-circuit.
///
/// Padding slots are not Orchard diversified addresses: `g_d_pad` is
/// hash-to-curve under [`PADDING_PERSONALIZATION`] (domain-separated from
/// Orchard's `DiversifyHash`) and `pk_d_pad = [ivk_external] * g_d_pad`.
/// Callers must supply the same `slot_index`, `rho`, and `rseed` the
/// delegation builder will see during proving (e.g. via
/// [`PaddedNoteData`]) so the off-circuit `cmx`/`nullifier` agree with
/// the circuit's witnessed values bit-for-bit.
///
/// Valid `slot_index` values are circuit padding slots `1..MAX_REAL_NOTES`
/// (`1..=4` for the current fixed-width circuit); slot `0` is always a real
/// note slot and `MAX_REAL_NOTES` is outside the circuit shape.
///
/// Returns [`DelegationBuildError::InvalidPaddingSlotIndex`],
/// [`DelegationBuildError::InvalidPaddingPoint`],
/// [`DelegationBuildError::InvalidPaddingNoteCommitment`], or
/// [`DelegationBuildError::InvalidPaddingNullifier`] for the
/// slot validation error and cryptographically negligible failure modes
/// (identity point, Sinsemilla bottom, identity nullifier point). Errors are reported against
/// [`PrecomputedRandomnessLocation::PaddedNote`] with the supplied
/// `slot_index`.
pub fn synthetic_padding_note_parts(
    fvk: &FullViewingKey,
    slot_index: usize,
    rho: Rho,
    rseed: RandomSeed,
) -> Result<SyntheticPaddingNoteParts, DelegationBuildError> {
    let ak: SpendValidatingKey = fvk.clone().into();
    let ivk = external_ivk_scalar(fvk, &ak);
    let location = PrecomputedRandomnessLocation::PaddedNote(slot_index);
    let padding =
        derive_synthetic_padding_note(fvk.nk().inner(), ivk, slot_index, rho, rseed, location)?;

    Ok(SyntheticPaddingNoteParts {
        cmx: padding.cmx.to_repr(),
        nullifier: padding.real_nf.to_repr(),
    })
}

// A single padding note slot in the delegation.
struct PaddingSlot {
    witness: NoteSlotWitness,
    cmx: pallas::Base,
    v_raw: u64,
    gov_null: pallas::Base,
    #[cfg(test)]
    real_nf: pallas::Base,
}

#[allow(clippy::too_many_arguments)]
fn build_padding_slot(
    slot_index: usize,
    pad_idx: usize,
    nk: pallas::Base,
    dom: pallas::Base,
    ivk: pallas::Scalar,
    imt_provider: &impl ImtProvider,
    rng: &mut impl RngCore,
    precomputed: Option<&PrecomputedRandomness>,
) -> Result<PaddingSlot, DelegationBuildError> {
    let location = PrecomputedRandomnessLocation::PaddedNote(pad_idx);

    let (rho, rseed) = if let Some(pre) = precomputed {
        // Reuse randomness so the prover commits to the same values.
        if pad_idx >= pre.padded_notes.len() {
            return Err(DelegationBuildError::MissingPrecomputedPaddedNote {
                index: pad_idx,
                actual: pre.padded_notes.len(),
            });
        }
        let pd = &pre.padded_notes[pad_idx];
        let rho = Rho::from_bytes(&pd.rho)
            .into_option()
            .ok_or(DelegationBuildError::InvalidPrecomputedRho { index: pad_idx })?;
        let rseed = RandomSeed::from_bytes(pd.rseed, &rho)
            .into_option()
            .ok_or(DelegationBuildError::InvalidPrecomputedRseed { location })?;
        (rho, rseed)
    } else {
        let rho = Rho::from_nf_old(Nullifier::from_inner(pallas::Base::random(&mut *rng)));
        let rseed = random_seed_for_rho(&rho, &mut *rng);
        (rho, rseed)
    };

    let padding = derive_synthetic_padding_note(nk, ivk, slot_index, rho, rseed, location)?;
    let gov_null = gov_null_hash(nk, dom, padding.real_nf);
    let imt_proof = imt_provider.non_membership_proof(padding.real_nf)?;

    // Merkle path is unconstrained for zero-value padding because condition 10
    // is gated by v=0; IMT non-membership and address ownership still run.
    let merkle_path = MerklePath::dummy(&mut *rng);
    let witness = NoteSlotWitness {
        g_d: Value::known(padding.g_d_pad),
        pk_d: Value::known(padding.pk_d_pad),
        v: Value::known(NoteValue::ZERO),
        rho: Value::known(rho.into_inner()),
        psi: Value::known(padding.psi),
        rcm: Value::known(padding.rcm),
        cm: Value::known(padding.cm),
        path: Value::known(merkle_path.auth_path()),
        pos: Value::known(merkle_path.position()),
        imt_nf_bounds: Value::known(imt_proof.nf_bounds),
        imt_leaf_pos: Value::known(imt_proof.leaf_pos),
        imt_path: Value::known(imt_proof.path),
        is_internal: Value::known(false),
    };

    Ok(PaddingSlot {
        witness,
        cmx: padding.cmx,
        v_raw: 0,
        gov_null,
        #[cfg(test)]
        real_nf: padding.real_nf,
    })
}

